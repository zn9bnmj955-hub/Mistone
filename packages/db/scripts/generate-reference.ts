/**
 * Generates supabase/reference.sql: the data a PRODUCTION database needs
 * (sports, starting prices, settings, knowledge base of the assistant, legal
 * placeholders) — no demo account, club or tournament.
 * Run with `pnpm --filter @orgasport/db reference:gen`.
 *
 * Safe to run again after each deployment: sport configurations are updated
 * (the "enabled" switch is kept), everything else is only added when missing,
 * so prices, settings and texts edited in the administration are kept.
 */
import { createHash } from "node:crypto";
import { SPORTS } from "@orgasport/sports";
import { KB_DOCS } from "./kb-content";
import { APP_SETTINGS, LEGAL_PAGES, PRICING_PLANS } from "./reference-data";

const text = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const md5 = (v: string) => createHash("md5").update(v, "utf8").digest("hex");
const jsonb = (v: unknown) => `${text(JSON.stringify(v))}::jsonb`;

const out: string[] = [
  "-- GENERATED by packages/db/scripts/generate-reference.ts. Do not edit by hand.",
  "-- Production reference data. Safe to run again: existing rows are kept.",
  "begin;",
  "",
  "-- Sports: the configuration follows the code, the on/off switch stays as set.",
  ...SPORTS.map(
    (s) =>
      `insert into public.sports (slug, name, config, enabled, sort_order) values (${text(s.slug)}, ${text(s.name)}, ${jsonb(s)}, ${s.enabled}, ${s.sortOrder})\n` +
      `  on conflict (slug) do update set name = excluded.name, config = excluded.config, sort_order = excluded.sort_order, updated_at = now();`,
  ),
  "",
  "-- Starting prices (edit them in /admin/tarifs).",
  ...PRICING_PLANS.map(
    (p) =>
      `insert into public.pricing_plans (code, label, description, price_cents, currency, max_teams, active, sort_order) values ` +
      `(${text(p.code)}, ${text(p.label)}, ${text(p.description)}, ${p.price_cents}, 'eur', ${p.max_teams ?? "null"}, true, ${p.sort_order})\n` +
      `  on conflict (code) do nothing;`,
  ),
  "",
  "-- Settings.",
  ...APP_SETTINGS.map(
    ([key, value, description]) =>
      `insert into public.app_settings (key, value, description) values (${text(key)}, ${jsonb(value)}, ${text(description)}) on conflict (key) do nothing;`,
  ),
  "",
  "-- Knowledge base of the assistant (added once per title; texts edited in the admin are kept).",
  ...KB_DOCS.map(
    (d) =>
      `insert into public.kb_documents (title, sport_slug, source_url, kind, version_date, reviewed_at, body, published)\n` +
      `  select ${text(d.title)}, ${text(d.sport)}, ${text(d.source)}, ${text(d.kind)}, ${text(d.versionDate)}, ${text(d.reviewedAt)}, ${text(d.body)}, true\n` +
      `  where not exists (select 1 from public.kb_documents where title = ${text(d.title)});`,
  ),
  "-- Rulebook sheets added before they were dated: mark them as rules, with their dates.",
  ...KB_DOCS.filter((d) => d.kind === "rules").map(
    (d) =>
      `update public.kb_documents set kind = 'rules', version_date = ${text(d.versionDate)}, reviewed_at = ${text(d.reviewedAt)}\n` +
      `  where title = ${text(d.title)} and kind = 'help' and version_date is null;`,
  ),
  "-- Help sheets added before they were dated: date them only when their stored text is the current one",
  "-- (an older text, or one edited in the admin, stays undated; a date set in the admin is kept).",
  ...KB_DOCS.filter((d) => d.kind === "help" && d.reviewedAt).map(
    (d) =>
      `update public.kb_documents set reviewed_at = ${text(d.reviewedAt)} where title = ${text(d.title)} and kind = 'help' and reviewed_at is null and md5(body) = ${text(md5(d.body))};`,
  ),
  "",
  "-- Legal pages: empty placeholders, written later by the site owner.",
  ...LEGAL_PAGES.map(
    (l) => `insert into public.legal_pages (slug, title, body, published) values (${text(l.slug)}, ${text(l.title)}, '', false) on conflict (slug) do nothing;`,
  ),
  "",
  "commit;",
  "",
];

process.stdout.write(out.join("\n"));
